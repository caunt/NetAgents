using System.Security;

using Microsoft.CodeAnalysis;

namespace NetAgents.Analyzers.Tests.Packaging;

/// <summary>
/// Verifies the published package and its enforcement in real consumer builds.
/// </summary>
public sealed class PackageConsumptionTests
{
    private const string Enumeration = """
        namespace CustomerApp.Features;

        /// <summary>Describes how a count is encoded.</summary>
        public enum CountWidth
        {
            /// <summary>A whole-word count.</summary>
            Word,

            /// <summary>A single-byte count.</summary>
            Byte,

            /// <summary>A variable-length count.</summary>
            Variable,
        }
        """ + "\n";

    private const string Switches = """

            /// <summary>Measures the width.</summary>
            /// <param name="width">The width to measure.</param>
            /// <returns>The width in bytes.</returns>
            public static int MeasureWidth(CountWidth width)
            {
                return width switch
                {
                    CountWidth.Word => 4,
                    _ => 0,
                };
            }

            /// <summary>Names the width.</summary>
            /// <param name="width">The width to name.</param>
            /// <returns>The width name.</returns>
            public static string NameWidth(CountWidth width)
            {
                switch (width)
                {
                    case CountWidth.Word:
                        return "word";
                    default:
                        return "variable";
                }
            }
        }
        """ + "\n";

    private const string ValidSource = """
        namespace Consumer.Features;

        /// <summary>Provides the consumer entry point.</summary>
        public static class ExampleService
        {
            /// <summary>Returns the supplied recipient name.</summary>
            /// <param name="recipientName">The name shown in the greeting.</param>
            /// <returns>The supplied name.</returns>
            public static string CreateGreeting(string recipientName)
            {
                return recipientName;
            }
        }
        """ + "\n";

    /// <summary>
    /// Verifies ordinary consumer builds apply code fixes without PATH, a shell, or manual targets.
    /// </summary>
    [Fact]
    public async Task PackageAutomaticallyFormatsWithoutShell()
    {
        DirectoryInfo workspace = Directory.CreateTempSubdirectory(prefix: "netagents automatic & consumer-");

        try
        {
            string packagePath = Environment.GetEnvironmentVariable(variable: "NETAGENTS_PACKAGE_PATH")
                ?? await ConsumerBuild.PackAnalyzer(workspace.FullName);

            string version = PackageArtifact.VerifyPackageContents(packagePath);
            string projectPath = Path.Combine(workspace.FullName, path2: "Consumer.csproj");
            string sourceDirectory = Directory.CreateDirectory(Path.Combine(workspace.FullName, path2: "Features")).FullName;
            string sourcePath = Path.Combine(sourceDirectory, path2: "ExampleService.cs");
            string generatedPath = Path.Combine(sourceDirectory, path2: "Generated.g.cs");
            const string generatedSource = "// <auto-generated/>\ninternal class GeneratedThing{ }\n";

            string projectContent = $$"""
                <Project Sdk="Microsoft.NET.Sdk">
                  <PropertyGroup>
                    <TargetFramework>net10.0</TargetFramework>
                    <RootNamespace>CustomerApp</RootNamespace>
                    <ImplicitUsings>enable</ImplicitUsings>
                  </PropertyGroup>
                  <ItemGroup>
                    <PackageReference Include="NetAgents.Analyzers" Version="{{SecurityElement.Escape(version)}}" PrivateAssets="all" />
                  </ItemGroup>
                </Project>
                """;

            string sourceConfiguration = $$"""
                <configuration><packageSources><clear />
                <add key="local" value="{{SecurityElement.Escape(Path.GetDirectoryName(Path.GetFullPath(packagePath)))}}" />
                </packageSources></configuration>
                """;

            await File.WriteAllTextAsync(projectPath, projectContent);
            await File.WriteAllTextAsync(Path.Combine(workspace.FullName, path2: "NuGet.Config"), sourceConfiguration);
            await File.WriteAllTextAsync(generatedPath, generatedSource);

            string source = "using System.Text;\n" + ValidSource.Replace(oldValue: "string recipientName)", newValue: "\nstring recipientName\n)", StringComparison.Ordinal)
                .Replace(
                    oldValue: "return recipientName;",
                    newValue: "string greeting = string.Concat(\nrecipientName,\nstring.Empty\n);\nif (string.IsNullOrEmpty(greeting)) { System.Console.WriteLine(greeting); }\nreturn greeting;",
                    StringComparison.Ordinal
                );

            source = source.Replace(
                oldValue: "    /// <summary>Returns the supplied recipient name.</summary>",
                newValue: "    /// <summary>Runs the final action.</summary>\n    public static void ZebraAction() {}\n    /// <summary>Runs the first action.</summary>\n    public static void AlphaAction() {}\n    /// <summary>Returns the supplied recipient name.</summary>",
                StringComparison.Ordinal
            );

            await File.WriteAllTextAsync(sourcePath, source);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, ["restore", projectPath, "--packages", Path.Combine(workspace.FullName, path2: "packages")]);
            string[] buildArguments = ["build", projectPath, "--no-restore", "--nologo", "--verbosity", "quiet"];

            await VerifySyntaxErrors(workspace.FullName, sourcePath, projectPath);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            string formatted = await File.ReadAllTextAsync(sourcePath);
            // Moving a public type to another namespace is an API change the projects that
            // reference this one would only discover when they failed to compile (#36).
            Assert.Contains(expectedSubstring: "namespace Consumer.Features;", formatted, StringComparison.Ordinal);
            Assert.DoesNotContain(expectedSubstring: "namespace CustomerApp.Features;", formatted, StringComparison.Ordinal);
            Assert.Contains(expectedSubstring: "CreateGreeting(string recipientName)", formatted, StringComparison.Ordinal);
            Assert.True(
                formatted.IndexOf(value: "AlphaAction", StringComparison.Ordinal) < formatted.IndexOf(value: "ZebraAction", StringComparison.Ordinal)
            );
            Assert.Contains(expectedSubstring: "}\n\n    /// <summary>Returns", formatted, StringComparison.Ordinal);
            Assert.Contains(expectedSubstring: "string.Concat(recipientName, string.Empty)", formatted, StringComparison.Ordinal);
            Assert.DoesNotContain(expectedSubstring: "using System.Text;", formatted, StringComparison.Ordinal);
            Assert.Equal(generatedSource, await File.ReadAllTextAsync(generatedPath));
            DateTime modification = File.GetLastWriteTimeUtc(sourcePath);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            Assert.Equal(formatted, await File.ReadAllTextAsync(sourcePath));
            Assert.Equal(modification, File.GetLastWriteTimeUtc(sourcePath));

            // Former path overrides must not redirect the task, policy, or Roslyn host.
            string ignoredHost = Directory.CreateDirectory(Path.Combine(workspace.FullName, path2: "ignored-host")).FullName;
            await File.WriteAllTextAsync(Path.Combine(ignoredHost, path2: "Microsoft.CodeAnalysis.dll"), contents: "Not an assembly.");

            string[] pathOverrideArguments =
            [
                .. buildArguments,
                "-p:NetAgentsBuildTaskPath=" + Path.Combine(ignoredHost, path2: "missing-task.dll"),
                "-p:NetAgentsGlobalConfigurationPath=" + Path.Combine(ignoredHost, path2: "missing.globalconfig"),
                "-p:NetAgentsRoslynDirectory=" + ignoredHost,
            ];

            await File.WriteAllTextAsync(sourcePath, source);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, pathOverrideArguments, withoutShell: true);
            Assert.Equal(formatted, await File.ReadAllTextAsync(sourcePath));

            string conditionalAssignments = ValidSource
                .Replace(
                    oldValue: "<param name=\"recipientName\">The name shown in the greeting.</param>",
                    newValue: "<param name=\"builder\">The optional builder.</param>\n    /// <param name=\"length\">The required length.</param>",
                    StringComparison.Ordinal
                )
                .Replace(oldValue: "    /// <returns>The supplied name.</returns>\n", string.Empty, StringComparison.Ordinal)
                .Replace(
                    oldValue: "string CreateGreeting(string recipientName)",
                    newValue: "void UpdateLength(System.Text.StringBuilder? builder, int length)",
                    StringComparison.Ordinal
                )
                .Replace(
                    oldValue: "return recipientName;",
                    newValue: "if (builder is not null)\n            builder.Length = length;\n        if (builder is not null)\n            builder.Capacity = length;",
                    StringComparison.Ordinal
                );

            await File.WriteAllTextAsync(sourcePath, conditionalAssignments);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            string simplifiedAssignments = await File.ReadAllTextAsync(sourcePath);
            Assert.Contains(expectedSubstring: "builder?.Length = length;", simplifiedAssignments, StringComparison.Ordinal);
            Assert.Contains(expectedSubstring: "builder?.Capacity = length;", simplifiedAssignments, StringComparison.Ordinal);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            Assert.Equal(simplifiedAssignments, await File.ReadAllTextAsync(sourcePath));

            string argumentNames = ValidSource.Replace(
                oldValue: "return recipientName;",
                newValue: "string padded = string.Empty.PadLeft(totalWidth: 4, ' ');\n\n        return string.Concat(str0: padded, recipientName);",
                StringComparison.Ordinal
            );

            await File.WriteAllTextAsync(sourcePath, argumentNames);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            string namedArguments = await File.ReadAllTextAsync(sourcePath);
            Assert.Contains(expectedSubstring: "PadLeft(totalWidth: 4, paddingChar: ' ')", namedArguments, StringComparison.Ordinal);
            Assert.Contains(expectedSubstring: "string.Concat(padded, recipientName)", namedArguments, StringComparison.Ordinal);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            Assert.Equal(namedArguments, await File.ReadAllTextAsync(sourcePath));

            const string tupleLocals = """
                    private static int SubtractCoordinates()
                    {
                        var firstPosition = (X: 1, Y: 2);
                        var secondPosition = (X: 1, Y: 2);
                        return firstPosition.X - secondPosition.X + firstPosition.Y - secondPosition.Y;
                    }

                    /// <summary>Resolves habitat bounds.</summary>
                    /// <param name="recipientName">The habitat name.</param>
                    /// <returns>The formatted habitat bounds.</returns>
                    internal static string Resolve(string recipientName)
                    {
                        var bounds = (Habitat: recipientName, Width: recipientName.Length, Height: recipientName.Length);
                        var habitat = bounds.Habitat;
                        var width = bounds.Width;
                        var height = bounds.Height;
                        return string.Concat(habitat, new string(c: ' ', width + height));
                    }

                """;

            string tupleSource = ValidSource
                .Replace(
                    oldValue: "    /// <summary>Returns the supplied recipient name.</summary>",
                    tupleLocals + "    /// <summary>Returns the supplied recipient name.</summary>",
                    StringComparison.Ordinal
                )
                .Replace(
                    oldValue: "return recipientName;",
                    newValue: "System.ArgumentNullException.ThrowIfNull(recipientName);\nvar habitat = Resolve(recipientName);\nvar coordinateOffset = SubtractCoordinates();\nreturn string.Concat(habitat, new string(c: ' ', coordinateOffset));",
                    StringComparison.Ordinal
                );

            await File.WriteAllTextAsync(sourcePath, tupleSource);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            string renamedTuple = await File.ReadAllTextAsync(sourcePath);
            Assert.Contains(
                expectedSubstring: "(string Habitat, int Width, int Height) bounds = (Habitat: recipientName, Width: recipientName.Length, Height: recipientName.Length);",
                renamedTuple,
                StringComparison.Ordinal
            );
            Assert.Contains(expectedSubstring: "string habitat = bounds.Habitat;", renamedTuple, StringComparison.Ordinal);
            Assert.Contains(expectedSubstring: "int width = bounds.Width;", renamedTuple, StringComparison.Ordinal);
            Assert.Contains(expectedSubstring: "int height = bounds.Height;", renamedTuple, StringComparison.Ordinal);
            Assert.Contains(expectedSubstring: "(int X, int Y) firstPosition = (X: 1, Y: 2);", renamedTuple, StringComparison.Ordinal);
            Assert.Contains(expectedSubstring: "(int X, int Y) secondPosition = (X: 1, Y: 2);", renamedTuple, StringComparison.Ordinal);
            Assert.DoesNotContain(expectedSubstring: "(int x, int y)", renamedTuple, StringComparison.Ordinal);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            Assert.Equal(renamedTuple, await File.ReadAllTextAsync(sourcePath));

            string manyTupleMethods = string.Join(
                Environment.NewLine,
                Enumerable.Range(start: 0, count: 70).Select(
                    static index => $$"""
                        internal static string ResolveBounds{{index}}(string value)
                        {
                            var bounds = (Habitat: value, Width: value.Length, Height: value.Length);
                            var habitat = bounds.Habitat;
                            var width = bounds.Width;
                            var height = bounds.Height;
                            return string.Concat(habitat, new string(c: ' ', width + height));
                        }
                    """
                )
            );

            string manyTupleSource = ValidSource.Replace(oldValue: "    }\n}\n", $"    }}\n\n{manyTupleMethods}\n}}\n", StringComparison.Ordinal);
            await File.WriteAllTextAsync(sourcePath, manyTupleSource);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            string renamedManyTuples = await File.ReadAllTextAsync(sourcePath);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            Assert.Equal(renamedManyTuples, await File.ReadAllTextAsync(sourcePath));

            string longName = new(c: 'p', count: 130);

            string longSource = ValidSource.Replace(oldValue: "return recipientName;", newValue: "return string.Concat(recipientName, string.Empty);", StringComparison.Ordinal)
                .Replace(oldValue: "recipientName", longName, StringComparison.Ordinal);

            await File.WriteAllTextAsync(sourcePath, longSource);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            string expanded = await File.ReadAllTextAsync(sourcePath);
            Assert.Contains(expectedSubstring: "CreateGreeting(\n", expanded, StringComparison.Ordinal);
            Assert.Contains(expectedSubstring: "string.Concat(\n", expanded, StringComparison.Ordinal);

            // An unresolved symbol stays a compiler error: no generated declaration, no formatting failure.
            string unresolvedSource = ValidSource.Replace(
                oldValue: "return recipientName;",
                newValue: "System.Console.WriteLine(payload);\n\n        return recipientName;",
                StringComparison.Ordinal
            );

            // Nothing else here needs repairing, and the namespace is left to its author (#36),
            // so a run that reports the compiler error must leave the file exactly as written.
            string expectedUnresolved = unresolvedSource;

            await File.WriteAllTextAsync(sourcePath, unresolvedSource);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, expectedDiagnosticIdentifier: "CS0103", withoutShell: true);
            Assert.Equal(expectedUnresolved, await File.ReadAllTextAsync(sourcePath));

            // An argument the compiler rejects stays a compiler error too: no generated overload (#31).
            string mismatchSource = ValidSource.Replace(
                oldValue: "return recipientName;",
                newValue: "System.ReadOnlyMemory<byte>? document = null;\n\n        Validate(document);\n\n        return recipientName;",
                StringComparison.Ordinal
            )
                .Replace(
                    oldValue: "    }\n}\n",
                    newValue: "    }\n\n    private static void Validate(System.Memory<byte>? data)\n    {\n        System.Console.WriteLine(data.HasValue);\n    }\n}\n",
                    StringComparison.Ordinal
                );

            await File.WriteAllTextAsync(sourcePath, mismatchSource);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, expectedDiagnosticIdentifier: "CS1503", withoutShell: true);
            string mismatched = await File.ReadAllTextAsync(sourcePath);
            Assert.DoesNotContain(expectedSubstring: "NotImplementedException", mismatched, StringComparison.Ordinal);
            Assert.Contains(expectedSubstring: "Validate(document);", mismatched, StringComparison.Ordinal);

            // A default arm already handles the remaining members, so populate-switch must not run (#32).
            string widthPath = Path.Combine(sourceDirectory, path2: "CountWidth.cs");

            string switchSource = ValidSource.Replace(oldValue: "namespace Consumer.Features;", newValue: "namespace CustomerApp.Features;", StringComparison.Ordinal)
                .Replace(oldValue: "    }\n}\n", "    }\n" + Switches, StringComparison.Ordinal);

            await File.WriteAllTextAsync(widthPath, Enumeration);
            await File.WriteAllTextAsync(sourcePath, switchSource);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            string switches = await File.ReadAllTextAsync(sourcePath);

            // The statement switch still becomes an expression, but neither switch gains an arm that
            // would take precedence over the catch-all that already answered for those members.
            Assert.DoesNotContain(expectedSubstring: "NotImplementedException", switches, StringComparison.Ordinal);
            Assert.DoesNotContain(expectedSubstring: "CountWidth.Byte", switches, StringComparison.Ordinal);
            Assert.DoesNotContain(expectedSubstring: "CountWidth.Variable", switches, StringComparison.Ordinal);
            Assert.Contains(expectedSubstring: "_ => 0,", switches, StringComparison.Ordinal);
            Assert.Contains(expectedSubstring: "_ => \"variable\",", switches, StringComparison.Ordinal);
            Assert.Equal(Enumeration, await File.ReadAllTextAsync(widthPath));
            File.Delete(widthPath);

            // Parentheses around one inferred lambda parameter are optional, so the build drops them (#0026).
            string lambdaSource = ValidSource.Replace(
                oldValue: "return recipientName;",
                newValue: "System.Func<string, string> echo = (name) => name;\n\n        return echo(recipientName);",
                StringComparison.Ordinal
            );

            await File.WriteAllTextAsync(sourcePath, lambdaSource);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            string lambdas = await File.ReadAllTextAsync(sourcePath);

            // The SDK also makes the lambda static, so only the parentheses are asserted here.
            Assert.Contains(expectedSubstring: "name => name;", lambdas, StringComparison.Ordinal);
            Assert.DoesNotContain(expectedSubstring: "(name) =>", lambdas, StringComparison.Ordinal);

            // A lambda holding statements keeps its argument list expanded, where joining it used to fight
            // statement spacing until the run gave up; written on one line, it is laid out the same way (#38).
            string statementsSource = ValidSource.Replace(
                oldValue: "return recipientName;",
                newValue: "string[] greetings = Array.ConvertAll(\n            [recipientName],\n            static name =>\n            {\n                string trimmed = name.Trim();\n\n                return trimmed.Length > 0 ? trimmed : name;\n            }\n        );\n\n        return greetings[0];",
                StringComparison.Ordinal
            );

            await File.WriteAllTextAsync(sourcePath, statementsSource);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            Assert.Equal(statementsSource, await File.ReadAllTextAsync(sourcePath));

            string joinedStatements = statementsSource.Replace(
                oldValue: "(\n            [recipientName],\n            static name =>\n            {\n                string trimmed = name.Trim();\n\n                return trimmed.Length > 0 ? trimmed : name;\n            }\n        );",
                newValue: "([recipientName], static name => { string trimmed = name.Trim(); return trimmed.Length > 0 ? trimmed : name; });",
                StringComparison.Ordinal
            );

            await File.WriteAllTextAsync(sourcePath, joinedStatements);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            Assert.Equal(statementsSource, await File.ReadAllTextAsync(sourcePath));

            // A qualified type is imported and named directly instead (#0027).
            string qualifiedSource = ValidSource.Replace(
                oldValue: "return recipientName;",
                newValue: "System.Text.StringBuilder builder = new(recipientName);\n\n        return builder.ToString();",
                StringComparison.Ordinal
            );

            await File.WriteAllTextAsync(sourcePath, qualifiedSource);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            string imported = await File.ReadAllTextAsync(sourcePath);
            Assert.Contains(expectedSubstring: "using System.Text;", imported, StringComparison.Ordinal);
            Assert.Contains(expectedSubstring: "StringBuilder builder = new(", imported, StringComparison.Ordinal);
            Assert.DoesNotContain(expectedSubstring: "System.Text.StringBuilder", imported, StringComparison.Ordinal);

            // An index from the end is a System.Index, not a literal the rule can name (#34).
            string indexSource = ValidSource.Replace(oldValue: "namespace Consumer.Features;", newValue: "namespace CustomerApp.Features;", StringComparison.Ordinal)
                .Replace(
                    oldValue: "return recipientName;",
                    newValue: "List<Version> versions = [];\n\n        return versions.Count > 0 ? versions[^1].ToString() : recipientName;",
                    StringComparison.Ordinal
                );

            await File.WriteAllTextAsync(sourcePath, indexSource);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            Assert.Equal(indexSource, await File.ReadAllTextAsync(sourcePath));

            // Formatting runs before compilation, so a build that fails afterwards still rewrites the
            // file. The log names every rewritten path so a dirty tree is never a surprise (#11).
            string relativeSourcePath = Path.Combine(path1: "Features", path2: "ExampleService.cs");
            string[] reportingArguments = ["build", projectPath, "--no-restore", "--nologo", "--verbosity", "minimal"];

            await File.WriteAllTextAsync(sourcePath, source);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, reportingArguments, expectedOutput: ["NetAgents rewrote " + relativeSourcePath], withoutShell: true);

            // A separate MSBuild invocation reuses completed formatting, including rejected suggestions.
            await ConsumerBuild.RunDevelopmentKit(
                workspace.FullName,
                reportingArguments,
                expectedOutput: ["inputs unchanged; reusing completed formatting"],
                forbiddenOutput: ["NetAgents rewrote", "analyzing project", "loading analyzers and code-fix providers"],
                withoutShell: true
            );

            // Generated inputs affect binding even though the formatter never rewrites them.
            await File.WriteAllTextAsync(generatedPath, generatedSource + "// Changed generated input.\n");
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, reportingArguments, expectedOutput: ["analyzing project"], withoutShell: true);
            string cachePath = Assert.Single(Directory.GetFiles(workspace.FullName, searchPattern: "*.NetAgents.formatting.cache", SearchOption.AllDirectories));
            await File.WriteAllTextAsync(cachePath, contents: "incomplete cache record");
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, reportingArguments, expectedOutput: ["analyzing project"], withoutShell: true);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, ["clean", projectPath, "--nologo", "--verbosity", "quiet"], withoutShell: true);
            Assert.False(File.Exists(cachePath));
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, reportingArguments, expectedOutput: ["analyzing project"], withoutShell: true);

            // Content hashing must detect an edit that MSBuild's timestamp checks could miss.
            DateTime formattedTime = File.GetLastWriteTimeUtc(sourcePath);
            string currentSource = await File.ReadAllTextAsync(sourcePath);
            await File.WriteAllTextAsync(sourcePath, currentSource.Replace(oldValue: "return greeting;", newValue: "return  greeting;", StringComparison.Ordinal));
            File.SetLastWriteTimeUtc(sourcePath, formattedTime);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, reportingArguments, expectedOutput: ["analyzing project", "NetAgents rewrote"], withoutShell: true);

            await ConsumerBuild.RunDevelopmentKit(
                workspace.FullName,
                [.. reportingArguments, "-p:Nullable=disable"],
                expectedDiagnosticIdentifier: "NETAGENTS0014",
                withoutShell: true
            );

            string blockedSource = ValidSource.Replace(
                oldValue: "return recipientName;",
                newValue: "recipientName.Trim();\n\n        return string.Concat(\nrecipientName,\nstring.Empty\n);",
                StringComparison.Ordinal
            );

            await File.WriteAllTextAsync(sourcePath, blockedSource);
            await ConsumerBuild.RunDevelopmentKit(
                workspace.FullName,
                reportingArguments,
                expectedDiagnosticIdentifier: "NETAGENTS0015",
                expectedOutput: ["NetAgents rewrote " + relativeSourcePath, "NetAgents rewrote 1 file before this build failed on diagnostics no fix repairs: NETAGENTS0015", "NETAGENTS0015"],
                withoutShell: true
            );

            // A diagnostic no fix repairs is a finished run: the formatting is recorded so the next
            // build reuses it, and the compiler reports the diagnostic again from the same source.
            Assert.True(File.Exists(cachePath));

            // The failing build kept its rewrite, which is why the report has to name it.
            Assert.Contains(
                expectedSubstring: "string.Concat(recipientName, string.Empty)",
                await File.ReadAllTextAsync(sourcePath),
                StringComparison.Ordinal
            );

            await File.WriteAllTextAsync(sourcePath, source);
            await ConsumerBuild.RunDevelopmentKit(
                workspace.FullName,
                arguments: ["msbuild", projectPath, "-t:FormatNetAgentsConsumerSource", "-p:DesignTimeBuild=true"],
                withoutShell: true
            );
            Assert.Equal(source, await File.ReadAllTextAsync(sourcePath));

            string multiTargetProject = projectContent.Replace(
                oldValue: "<TargetFramework>net10.0</TargetFramework>",
                newValue: "<TargetFrameworks>net10.0;net10.0-windows</TargetFrameworks>",
                StringComparison.Ordinal
            );

            string conditionalSource = ValidSource.Replace(
                oldValue: "return recipientName;",
                newValue: "\n#if WINDOWS\nreturn string.Concat(\nrecipientName,\nstring.Empty\n);\n#else\nreturn string.Concat(\nrecipientName,\nstring.Empty\n);\n#endif",
                StringComparison.Ordinal
            );

            await File.WriteAllTextAsync(projectPath, multiTargetProject);
            await File.WriteAllTextAsync(sourcePath, conditionalSource);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, ["restore", projectPath, "--packages", Path.Combine(workspace.FullName, path2: "packages")]);
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, withoutShell: true);
            string multiTargetSource = await File.ReadAllTextAsync(sourcePath);
            Assert.Equal(expected: 3, multiTargetSource.Split(separator: "string.Concat(recipientName, string.Empty)", StringSplitOptions.None).Length);
            Assert.True(File.Exists(Path.Combine(workspace.FullName, path2: "bin/Debug/net10.0/Consumer.dll")));
            Assert.True(File.Exists(Path.Combine(workspace.FullName, path2: "bin/Debug/net10.0-windows/Consumer.dll")));
            // The first target must observe the shared-source rewrite made by the second target.
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, reportingArguments, withoutShell: true);
            await ConsumerBuild.RunDevelopmentKit(
                workspace.FullName,
                reportingArguments,
                expectedOutput: ["formatting Consumer: pass 0", "inputs unchanged; reusing completed formatting"],
                forbiddenOutput: ["analyzing project"],
                withoutShell: true
            );
            Assert.Equal(
                expected: 2,
                Directory.GetFiles(workspace.FullName, searchPattern: "*.NetAgents.formatting.cache", SearchOption.AllDirectories).Length
            );

            await File.WriteAllTextAsync(
                sourcePath,
                ValidSource.Replace(
                    oldValue: "string CreateGreeting(string recipientName)",
                    newValue: "System.IComparable CreateGreeting(int recipientName)",
                    StringComparison.Ordinal
                )
            );
            await ConsumerBuild.RunDevelopmentKit(workspace.FullName, buildArguments, expectedDiagnosticIdentifier: "NETAGENTS0001", withoutShell: true);
        }
        finally
        {
            workspace.Delete(recursive: true);
        }
    }

    /// <summary>
    /// Verifies SDK defaults, consumer diagnostics, and rejected policy overrides.
    /// </summary>
    [Fact]
    public async Task PackageEnforcesPolicyInConsumerBuilds()
    {
        DirectoryInfo workspace = Directory.CreateTempSubdirectory(prefix: "netagents-package-consumer-");

        try
        {
            string packagePath = Environment.GetEnvironmentVariable(variable: "NETAGENTS_PACKAGE_PATH")
                ?? await ConsumerBuild.PackAnalyzer(workspace.FullName);

            packagePath = Path.GetFullPath(packagePath);
            string packageVersion = PackageArtifact.VerifyPackageContents(packagePath);
            await PackageArtifact.VerifyConfigurationMatchesTemplate(workspace.FullName, packagePath);
            string projectPath = Path.Combine(paths: [workspace.FullName, "Consumer.csproj"]);
            string sourcePath = Path.Combine(paths: [workspace.FullName, "ExampleService.cs"]);

