using System.Collections.Immutable;
using System.Diagnostics.CodeAnalysis;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CodeActions;
using Microsoft.CodeAnalysis.CodeFixes;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

using NetAgents.Analyzers.CodeFixes.Formatting;
using NetAgents.Analyzers.Formatting;
using NetAgents.Analyzers.Tests.Infrastructure;
using NetAgents.BuildTasks;

namespace NetAgents.Analyzers.Tests.Formatting.Documents;

/// <summary>Checks that the formatter rewrites exactly the documents the analyzers read (#39).</summary>
public sealed class EditableDocumentsTests
{
    private const string GeneratedSource = "// <auto-generated/>\nclass Generated\n{\n    private static int Value;\n}\n";

    /// <summary>Fixes the documents it may rewrite even when a project-wide fix would reach a generated one.</summary>
    /// <param name="reach">How far the project-wide fix goes: the documents its diagnostics name, or every document.</param>
    [Theory]
    [InlineData(PrivateFieldFix.DiagnosedDocuments)]
    [InlineData(PrivateFieldFix.EveryDocument)]
    public async Task FixesEditableDocumentsBesideGeneratedOnes(string reach)
    {
        using AdhocWorkspace workspace = new();

        Project project = CreateProject(workspace, name: "Editable.cs", source: "class Editable\n{\n    private static int Value;\n}\n")
            .AddDocument(name: "Generated.g.cs", SourceText.From(GeneratedSource), filePath: "/workspace/Generated.g.cs").Project;

        Project result = (await CodeFixRunner.Fix(project, [new PrivateFieldAnalyzer()], [new PrivateFieldFix(reach)], static fault => Assert.Fail(fault), CancellationToken.None))
            .Project;

        Assert.Contains(expectedSubstring: "internal static int Value;", await ReadDocument(result, name: "Editable.cs"), StringComparison.Ordinal);
        Assert.Equal(GeneratedSource, await ReadDocument(result, name: "Generated.g.cs"));
    }

    /// <summary>
    /// Fixes a file that only quotes the generated-code marker, and the file beside it that a project-wide
    /// fix used to leave behind with it.
    /// </summary>
    [Fact]
    public async Task FixesEveryFileBesideOneThatQuotesTheMarker()
    {
        const string plain = "class Alpha\n{\n    void Write()\n    {\n        System.Console.WriteLine(\n            string.Empty\n        );\n    }\n}\n";

        const string quoting = "class Beta\n{\n    const string Sample = \"// <auto-generated/>\";\n\n    void Write()\n    {\n"
            + "        System.Console.WriteLine(\n            Sample\n        );\n    }\n}\n";

        using AdhocWorkspace workspace = new();

        Project project = CreateProject(workspace, name: "Alpha.cs", plain)
            .AddDocument(name: "Beta.cs", SourceText.From(quoting), filePath: "/workspace/Beta.cs").Project;

        Project result = (await CodeFixRunner.Fix(
            project,
            [new ArgumentLayoutAnalyzer()],
            [new ArgumentLayoutCodeFixProvider()],
            static fault => Assert.Fail(fault),
            CancellationToken.None
        )).Project;

        string alpha = await ReadDocument(result, name: "Alpha.cs");
        string beta = await ReadDocument(result, name: "Beta.cs");

        Assert.Contains(expectedSubstring: "System.Console.WriteLine(string.Empty);", alpha, StringComparison.Ordinal);
        Assert.Contains(expectedSubstring: "System.Console.WriteLine(Sample);", beta, StringComparison.Ordinal);
    }

    /// <summary>Follows generated_code in configuration in both directions, as the analyzers do.</summary>
    /// <param name="name">The document's file name.</param>
    /// <param name="generated">The generated_code value configured for it.</param>
    /// <param name="outcome">What the formatter does with the document: "kept" or "rewritten".</param>
    [Theory]
    [InlineData("Example.cs", "true", "kept")]
    [InlineData("Example.g.cs", "false", "rewritten")]
    public async Task FollowsGeneratedCodeConfiguration(string name, string generated, string outcome)
    {
        const string source = "class Example\n{\n    void Run( ) { }\n}\n";

        using AdhocWorkspace workspace = new();

        Project project = CreateProject(workspace, name, source)
            .AddAnalyzerConfigDocument(
                name: ".editorconfig",
                SourceText.From($"root = true\n\n[*.cs]\ngenerated_code = {generated}\n"),
                filePath: "/workspace/.editorconfig"
            ).Project;

        Project result = (await CodeFixRunner.Fix(project, [], [], static fault => Assert.Fail(fault), CancellationToken.None)).Project;
        string text = await ReadDocument(result, name);

        Assert.Equal(outcome == "kept", text == source);
    }

    /// <summary>Formats a document that only quotes the generated-code marker, which the analyzers still read.</summary>
    [Fact]
    public async Task FormatsFilesThatOnlyQuoteTheMarker()
    {
        const string source = "class Example\n{\n    const string Sample = \"// <auto-generated/>\";\n\n    void Run( ) { }\n}\n";

        using AdhocWorkspace workspace = new();

        Project result = (await CodeFixRunner.Fix(CreateProject(workspace, name: "Example.cs", source), [], [], static fault => Assert.Fail(fault), CancellationToken.None))
            .Project;

        Assert.Contains(expectedSubstring: "void Run() { }", await ReadDocument(result, name: "Example.cs"), StringComparison.Ordinal);
    }

    private static Project CreateProject(AdhocWorkspace workspace, string name, string source)
    {
        return workspace.AddProject(name: "Documents", LanguageNames.CSharp)
            .WithCompilationOptions(new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary))
            .AddMetadataReferences(AnalyzerTestHarness.References)
            .AddDocument(name, SourceText.From(source), filePath: "/workspace/" + name).Project;
    }

    private static async Task<string> ReadDocument(Project project, string name)
    {
        Document document = project.Documents.Single(candidate => candidate.Name == name);

        return (await document.GetTextAsync().ConfigureAwait(continueOnCapturedContext: false)).ToString();
    }

    // Reports private fields in generated code too, as an analyzer that opts into it does.
    [SuppressMessage(
        "MicrosoftCodeAnalysisCorrectness",
        "RS1001",
        Justification = "This private test analyzer is constructed explicitly and must not be discovered by compiler hosts."
    )]
    [SuppressMessage(
        "MicrosoftCodeAnalysisReleaseTracking",
        "RS2008",
        Justification = "This private test rule is only used in tests and is not shipped."
    )]
    private sealed class PrivateFieldAnalyzer : DiagnosticAnalyzer
    {
        public const string Identifier = "TEST0201";

        private static readonly DiagnosticDescriptor Rule = new(
            Identifier,
            title: "Private field",
            messageFormat: "Make the field internal",
            category: "Testing",
            DiagnosticSeverity.Warning,
            isEnabledByDefault: true
        );

        public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => [Rule];

        public override void Initialize(AnalysisContext context)
        {
            context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
            context.EnableConcurrentExecution();
            context.RegisterSyntaxNodeAction(Report, SyntaxKind.FieldDeclaration);
        }

        private static void Report(SyntaxNodeAnalysisContext context)
        {
            foreach (SyntaxToken modifier in ((FieldDeclarationSyntax)context.Node).Modifiers)
            {
                if (modifier.IsKind(SyntaxKind.PrivateKeyword))
                    context.ReportDiagnostic(Diagnostic.Create(Rule, modifier.GetLocation()));
            }
        }
    }

    // Makes a private field internal; its project-wide form either follows its diagnostics or edits every document.
    private sealed class PrivateFieldFix(string reach) : CodeFixProvider
    {
        public const string DiagnosedDocuments = "diagnosed documents";

        public const string EveryDocument = "every document";

        public override ImmutableArray<string> FixableDiagnosticIds => [PrivateFieldAnalyzer.Identifier];

        public override FixAllProvider GetFixAllProvider()
        {
            return reach == EveryDocument ? new EveryDocumentFixAll() : WellKnownFixAllProviders.BatchFixer;
        }

        public override Task RegisterCodeFixesAsync(CodeFixContext context)
        {
            context.RegisterCodeFix(
                CodeAction.Create(
                    title: "Make the field internal",
                    cancellationToken => MakeInternal(context.Document, cancellationToken),
                    equivalenceKey: "internal"
                ),
                context.Diagnostics
            );

            return Task.CompletedTask;
        }

        private static async Task<Document> MakeInternal(Document document, CancellationToken cancellationToken)
        {
            SourceText text = await document.GetTextAsync(cancellationToken).ConfigureAwait(continueOnCapturedContext: false);

            return document.WithText(SourceText.From(text.ToString().Replace(oldValue: "private static", newValue: "internal static", StringComparison.Ordinal)));
        }

        // Ignores the diagnostics it is handed, as a provider that rewrites a whole project might.
        private sealed class EveryDocumentFixAll : FixAllProvider
        {
            public override Task<CodeAction?> GetFixAsync(FixAllContext fixAllContext)
            {
                CodeAction action = CodeAction.Create(
                    title: "Make every field internal",
                    async cancellationToken =>
                    {
                        Solution solution = fixAllContext.Project.Solution;

                        foreach (DocumentId identifier in fixAllContext.Project.DocumentIds)
                        {
                            Document document = solution.GetDocument(identifier) ?? throw new InvalidOperationException(message: "A project document is missing.");
                            solution = (await MakeInternal(document, cancellationToken).ConfigureAwait(continueOnCapturedContext: false)).Project.Solution;
                        }

                        return solution;
                    },
                    equivalenceKey: "internal"
                );

                return Task.FromResult<CodeAction?>(action);
            }
        }
    }
}
