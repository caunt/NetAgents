namespace NetAgents.Analyzers.Tests.Policy;

/// <summary>
/// Covers the C# written in Razor components and views, which reaches the analyzers inside generated code.
/// </summary>
public sealed class RazorCodeTests
{
    // The shape the Razor source generator emits: scaffolding behind #line hidden or before the first
    // directive, and each stretch copied from the Razor file after a #line directive naming that file.
    private const string Component = """
        // <auto-generated/>
        #pragma warning disable 1591
        namespace RazorSample
        {
            #line default
            using global::System;
            using global::System.Threading.Tasks;
            #line default
            #line hidden
            #nullable restore
            public partial class Sample : global::RazorSample.ComponentBase
            #nullable disable
            {
                #pragma warning disable 1998
                protected override void BuildRenderTree(global::RazorSample.RenderTreeBuilder __builder)
                {
                    __builder.OpenElement(0, "p");
        RENDER
                    __builder.CloseElement();
                }
                #pragma warning restore 1998
        GENERATED
        #nullable restore
        #line (3,8)-(17,1) "RAZOR"
        MEMBERS
        #line default
        #line hidden
        #nullable disable
            }
        }
        #pragma warning restore 1591
        """;

    // The framework types the generated code calls, generated themselves so no rule reads them.
    private const string Framework = """
        // <auto-generated/>
        #nullable enable
        namespace RazorSample
        {
            public abstract class ComponentBase
            {
                protected abstract void BuildRenderTree(RenderTreeBuilder builder);

                protected static object? Describe(global::System.Action work, int value) => value;

                protected global::System.Threading.Tasks.Task InvokeAsync(global::System.Action work)
                {
                    work();
                    return global::System.Threading.Tasks.Task.CompletedTask;
                }

                protected void StateHasChanged()
                {
                }
            }

            public sealed class RenderTreeBuilder
            {
                public void AddAttribute(int sequence, string name, object? value)
                {
                }

                public void AddContent(int sequence, object? content)
                {
                }

                public void CloseElement()
                {
                }

                public void OpenElement(int sequence, string elementName)
                {
                }
            }

            public static class EventCallback
            {
                public static object Create(object receiver, global::System.Action callback) => callback;
            }
        }
        """;

    // The code block from issue #37, starting after "@code {" on line 3 of the component.
    private const string IssueMembers = """

            private string _status = string.Empty;

            private void Report(string status)
            {
                _status = status;
                _ = InvokeAsync(StateHasChanged);
            }

            private static async Task RunAsync(Func<Task> action)
            {
                try { await action(); }
                catch (InvalidOperationException) { }
            }

        """;

    /// <summary>
    /// Verifies a Razor file's own lambdas and statements are checked where markup holds them.
    /// </summary>
    [Fact]
    public async Task ChecksLambdasAndStatementsWrittenInMarkup()
    {
        const string handler = """
                        __builder.AddAttribute(1, "onclick", global::RazorSample.EventCallback.Create(this,
            #nullable restore
            #line (1,22)-(1,98) "RAZOR"
            () => { try { StateHasChanged(); } catch (InvalidOperationException) { } }

            #line default
            #line hidden
            #nullable disable
                        ));
            """;

        const string statement = """
            #nullable restore
            #line (1,3)-(1,36) "RAZOR"
            _ = InvokeAsync(StateHasChanged);

            #line default
            #line hidden
            #nullable disable
            """;

        Diagnostic caught = Assert.Single(await AnalyzerTestHarness.Analyze(new EmptyCatchBlockAnalyzer(), CreateComponent(members: string.Empty, render: handler)));
        Diagnostic discarded = Assert.Single(await AnalyzerTestHarness.Analyze(new IgnoredReturnValueAnalyzer(), CreateComponent(members: string.Empty, render: statement)));

        Assert.Equal(expected: "Sample.razor(1,57)", DescribeLocation(caught));
        Assert.Equal(expected: "Sample.razor(1,3)", DescribeLocation(discarded));
    }

    /// <summary>
    /// Verifies Razor views count as Razor files while other files a #line directive names do not.
    /// </summary>
    [Fact]
    public async Task ChecksRazorViewsOnly()
    {
        const string member = "\n    private static void Swallow() { try { } catch { } }";

        SyntaxTree[] view = CreateComponent(member, razorPath: "/workspace/Index.cshtml");
        SyntaxTree[] window = CreateComponent(member, razorPath: "/workspace/MainWindow.xaml");
        Diagnostic reported = Assert.Single(await AnalyzerTestHarness.Analyze(new EmptyCatchBlockAnalyzer(), view));

        Assert.Equal(expected: "Index.cshtml(4,45)", DescribeLocation(reported));
        Assert.Empty(await AnalyzerTestHarness.Analyze(new EmptyCatchBlockAnalyzer(), window));
    }

    /// <summary>
    /// Verifies each rule that checks Razor code reports its violation where the author wrote it, and
    /// never in the scaffolding Razor generates around it.
    /// </summary>
    /// <param name="ruleIdentifier">The rule whose analyzer runs.</param>
    /// <param name="member">A component member violating that rule.</param>
    [Theory]
    [InlineData(BoxingConversionAnalyzer.RuleIdentifier, "private static object Box(int count) => count;")]
    [InlineData(UntypedValueAnalyzer.RuleIdentifier, "private static string? Format(object? state) => state?.ToString();")]
    [InlineData(LockStatementAnalyzer.RuleIdentifier, "private void Guard() { lock (this) { } }")]
    [InlineData(EmptyCatchBlockAnalyzer.RuleIdentifier, "private static void Swallow() { try { } catch { } }")]
    [InlineData(DescriptiveNameAnalyzer.RuleIdentifier, "private static int Measure(int x) => x;")]
    [InlineData(NullForgivingOperatorAnalyzer.RuleIdentifier, "private static string Require(string? name) => name!;")]
    [InlineData(UnconditionalLoopAnalyzer.RuleIdentifier, "private static void Spin() { while (true) { break; } }")]
    [InlineData(
        FrameworkSynchronizationAnalyzer.RuleIdentifier,
        "private static void Pause() { System.Threading.Thread.Sleep(millisecondsTimeout: 1); }"
    )]
    [InlineData(IgnoredReturnValueAnalyzer.RuleIdentifier, "private static void Trim(string text) { _ = text.Trim(); }")]
    [InlineData(TupleReturnTypeAnalyzer.RuleIdentifier, "private static (int Width, int Height) Measure() => (1, 2);")]
    public async Task ChecksTheCodeBlockOnly(string ruleIdentifier, string member)
    {
        SyntaxTree[] written = CreateComponent("\n    " + member);
        SyntaxTree[] generated = CreateComponent(members: string.Empty, generated: "        " + member);
        Diagnostic authored = Assert.Single(await AnalyzerTestHarness.Analyze(CreateAnalyzer(ruleIdentifier), written));

        Assert.Equal(ruleIdentifier, authored.Id);
        Assert.Equal(expected: "/workspace/Sample.razor", authored.Location.GetMappedLineSpan().Path);
        Assert.Empty(await AnalyzerTestHarness.Analyze(CreateAnalyzer(ruleIdentifier), generated));
    }

    /// <summary>
    /// Verifies a markup expression is judged by the generated call it is handed to, not by these rules,
    /// including generated code sharing its line ahead of where the Razor text starts.
    /// </summary>
    [Fact]
    public async Task IgnoresWhatMarkupHandsToGeneratedCalls()
    {
        const string prefix = "__builder.AddContent(2, Describe(() => { try { } catch { } }, ";
        string offset = prefix.Length.ToString(CultureInfo.InvariantCulture);

        // An int written in markup boxes into the object parameter Razor chose for it, and a lambda Razor
        // wrote ahead of an enhanced directive's offset shares a line Roslyn maps to the Razor file.
        string render = $$"""
            #nullable restore
            #line (1,5)-(1,11) 24 "RAZOR"
            __builder.AddContent(1, _count

            #line default
            #line hidden
            #nullable disable
                        );
                        __builder.AddAttribute(2, "data-count",
            #nullable restore
            #line (1,20)-(1,26) "RAZOR"
            _count

            #line default
            #line hidden
            #nullable disable
                        );
            #nullable restore
            #line (1,30)-(1,36) {{offset}} "RAZOR"
            {{prefix}}_count

            #line default
            #line hidden
            #nullable disable
                        ));
            """;

        SyntaxTree[] component = CreateComponent(members: "\n    private int _count = 1;\n", render: render);

        Assert.Empty(await AnalyzerTestHarness.Analyze(new BoxingConversionAnalyzer(), component));
        Assert.Empty(await AnalyzerTestHarness.Analyze(new EmptyCatchBlockAnalyzer(), component));
    }

    /// <summary>
    /// Verifies formatting rules stay with C# files, because no fix rewrites a Razor file.
    /// </summary>
    [Fact]
    public async Task LeavesFormattingRulesToCSharpFiles()
    {
        const string member = "public static string Pad(string text) => text.PadLeft(4);";

        Diagnostic plain = Assert.Single(await AnalyzerTestHarness.Analyze(new ExplicitLiteralArgumentNameAnalyzer(), $"public static class ExampleType {{ {member} }}"));
        Assert.Equal(ExplicitLiteralArgumentNameAnalyzer.RuleIdentifier, plain.Id);
        Assert.Empty(await AnalyzerTestHarness.Analyze(new ExplicitLiteralArgumentNameAnalyzer(), CreateComponent("\n    " + member)));
    }

    /// <summary>
    /// Verifies the component from issue #37 fails on the lines its author wrote.
    /// </summary>
    [Fact]
    public async Task ReportsCodeBlocksAtTheirRazorLines()
    {
        Diagnostic discarded = Assert.Single(await AnalyzerTestHarness.Analyze(new IgnoredReturnValueAnalyzer(), CreateComponent(IssueMembers)));
        Diagnostic swallowed = Assert.Single(await AnalyzerTestHarness.Analyze(new EmptyCatchBlockAnalyzer(), CreateComponent(IssueMembers)));

        Assert.Equal(expected: "Sample.razor(9,9)", DescribeLocation(discarded));
        Assert.Equal(expected: "Sample.razor(15,9)", DescribeLocation(swallowed));
    }

    private static DiagnosticAnalyzer CreateAnalyzer(string ruleIdentifier)
    {
        return ruleIdentifier switch
        {
            BoxingConversionAnalyzer.RuleIdentifier => new BoxingConversionAnalyzer(),
            UntypedValueAnalyzer.RuleIdentifier => new UntypedValueAnalyzer(),
            LockStatementAnalyzer.RuleIdentifier => new LockStatementAnalyzer(),
            EmptyCatchBlockAnalyzer.RuleIdentifier => new EmptyCatchBlockAnalyzer(),
            DescriptiveNameAnalyzer.RuleIdentifier => new DescriptiveNameAnalyzer(),
            NullForgivingOperatorAnalyzer.RuleIdentifier => new NullForgivingOperatorAnalyzer(),
            UnconditionalLoopAnalyzer.RuleIdentifier => new UnconditionalLoopAnalyzer(),
            FrameworkSynchronizationAnalyzer.RuleIdentifier => new FrameworkSynchronizationAnalyzer(),
            IgnoredReturnValueAnalyzer.RuleIdentifier => new IgnoredReturnValueAnalyzer(),
            TupleReturnTypeAnalyzer.RuleIdentifier => new TupleReturnTypeAnalyzer(),
            _ => throw new ArgumentOutOfRangeException(nameof(ruleIdentifier)),
        };
    }

    private static SyntaxTree[] CreateComponent(string members, string razorPath = "/workspace/Sample.razor", string render = "", string generated = "")
    {
        string source = Component.Replace(oldValue: "RENDER", render, StringComparison.Ordinal)
            .Replace(oldValue: "GENERATED", generated, StringComparison.Ordinal)
            .Replace(oldValue: "MEMBERS", members, StringComparison.Ordinal)
            .Replace(oldValue: "RAZOR", razorPath, StringComparison.Ordinal);

        CSharpParseOptions options = CSharpParseOptions.Default.WithLanguageVersion(LanguageVersion.CSharp14);

        return [CSharpSyntaxTree.ParseText(source, options, path: "Sample_razor.g.cs"), CSharpSyntaxTree.ParseText(Framework, options, path: "Framework.g.cs")];
    }

    private static string DescribeLocation(Diagnostic diagnostic)
    {
        FileLinePositionSpan span = diagnostic.Location.GetMappedLineSpan();

        return $"{Path.GetFileName(span.Path)}({span.StartLinePosition.Line + 1},{span.StartLinePosition.Character + 1})";
    }
}
